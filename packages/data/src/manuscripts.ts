/** 字数：去掉空白后的字符数（标点也算一个字，与各大文学站的算法一致；全角空格属于空白，不算） */
export function wordCount(paragraphs: readonly string[]): number {
  return paragraphs.reduce((sum, p) => sum + p.replace(/\s/g, '').length, 0);
}

