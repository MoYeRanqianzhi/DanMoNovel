/** 第 index 章（从 0 开始）的完整标题，例如"第十二章 雷阵雨" */
export function chapterTitle(book: Book, index: number): string {
  const label = `第${toChineseNumber(index + 1)}章`;
  const name = NAMED_CHAPTERS[book.id]?.[index];
  return name ? `${label} ${name}` : label;
}

