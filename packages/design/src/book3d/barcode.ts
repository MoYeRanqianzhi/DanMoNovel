/**
 * Code 128 条码（只用 C 字符集）：给封底印的书号编码（书号规则见 book-number 记忆）
 *
 * 书号是 16 位数字，装不进 EAN-13（只有 12 位数据），所以用同样通用、扫码枪与手机都认得的 Code 128。
 * C 字符集把两位数字编成一个符号，16 位书号只要 8 个数据符号，条码短而好认。
 *
 * 一个条码 = 起始符 C（值 105）+ 数据符号 + 校验符 + 终止符（值 106）。
 * 校验符 = (105 + Σ 第 i 个数据符号的值 × i) mod 103，i 从 1 起。
 * 每个符号写成 6 个黑白相间的宽度（以最窄的一条"模块"为单位，先黑后白，合计 11 个模块）；
 * 终止符是 7 个宽度、13 个模块。码表按 ISO/IEC 15417，2026-09-27 已与 JsBarcode 的码表逐项核对一致。
 */

/** 值 0~106 的符号宽度 */
const PATTERNS = (
  '212222 222122 222221 121223 121322 131222 122213 122312 132212 221213 ' +
  '221312 231212 112232 122132 122231 113222 123122 123221 223211 221132 ' +
  '221231 213212 223112 312131 311222 321122 321221 312212 322112 322211 ' +
  '212123 212321 232121 111323 131123 131321 112313 132113 132311 211313 ' +
  '231113 231311 112133 112331 132131 113123 113321 133121 313121 211331 ' +
  '231131 213113 213311 213131 311123 311321 331121 312113 312311 332111 ' +
  '314111 221411 431111 111224 111422 121124 121421 141122 141221 112214 ' +
  '112412 122114 122411 142112 142211 241211 221114 413111 241112 134111 ' +
  '111242 121142 121241 114212 124112 124211 411212 421112 421211 212141 ' +
  '214121 412121 111143 111341 131141 114113 114311 411113 411311 113141 ' +
  '114131 311141 411131 211412 211214 211232 2331112'
).split(' ');

const START_C = 105;
const STOP = 106;

/** 把偶数位的纯数字编成 Code 128C，返回从第一条黑条开始、黑白相间的宽度（单位：模块） */
export function code128c(digits: string): number[] {
  if (!/^(?:\d\d)+$/.test(digits)) throw new Error(`Code 128C 只能编码偶数位的数字：${digits}`);
  const values = [START_C];
  for (let i = 0; i < digits.length; i += 2) values.push(Number(digits.slice(i, i + 2)));
  // 起始符的权重是 1，第 i 个数据符号的权重是 i
  const check = values.reduce((sum, v, i) => sum + v * Math.max(1, i), 0) % 103;
  values.push(check, STOP);
  return values.flatMap((v) => Array.from(PATTERNS[v], Number));
}
